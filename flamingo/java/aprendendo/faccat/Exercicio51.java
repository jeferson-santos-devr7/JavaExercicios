package flamingo.java.aprendendo.faccat;

public class Exercicio51 {
    // Escreva um algoritmo para imprimir os números de 1 (inclusive)
    // a 10 (inclusive) em ordem decrescente

    static void main() {
        for(int i = 10; i >= 1; i--) {
            System.out.println(i);
        }
    }
}
